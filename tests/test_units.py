def test_dt_is_the_scalar_steps_per_frame_wants():
    """D-023: ``dt`` is seconds per timestep and grid size enters through it.

    Refining by two halves ``dt``, so the same playback speed asks for twice
    the steps — asserted here against the runner's own function, since this
    module is where D-023 says that scalar comes from.
    """
    from lbm.runner import steps_per_frame

    coarse = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, cells_per_length=40.0
    )
    fine = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, cells_per_length=80.0
    )
    assert fine.dt == pytest.approx(coarse.dt / 2.0)
    assert steps_per_frame(fine.dt) == pytest.approx(
        2 * steps_per_frame(coarse.dt), rel=0.02
    )


def test_the_rung_3_case_comes_out_of_the_units_path():
    """The cylinder of T007, described in physics, gives its lattice numbers.

    ``validate/cylinder.py`` runs a 21-cell disc at ``U = 0.06``, ``Re = 100``,
    and prints ``tau = 0.5378`` and ``dt = (U/U_phys)(D_phys/D_cells)``. Coming
    at the same case from metres and seconds must reproduce both.
    """
    u = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.10, re=100.0, cells_per_length=21.0, u_lattice=0.06
    )
    assert u.tau == pytest.approx(0.5378, abs=5e-5)
    assert u.dt == pytest.approx((0.06 / 1.0) * (0.10 / 21.0), rel=1e-12)
    assert u.nu == pytest.approx(0.06 * 21.0 / 100.0, rel=1e-12)


def test_the_physical_path_sets_rung_3_up_identically():
    """``validate.cylinder --physical`` must not be a *different* case.

    The 2% ``Cd`` criterion is measured by running the rung both ways, which
    takes minutes; what this test pins in milliseconds is the reason the two
    runs agree — ``tau``, the lattice ``U`` and ``dt`` come out the same to
    float precision, so the physics being integrated is identical.
    """
    from validate.cylinder import D_PHYS_M, RE, U, U_PHYS_MS, tau_for

    d_measured = 21.0
    nu_ref, tau_ref = tau_for(RE, U, d_measured)
    u = LatticeUnits.from_physical(
        u_phys=U_PHYS_MS,
        l_phys=D_PHYS_M,
        nu_phys=U_PHYS_MS * D_PHYS_M / RE,
        cells_per_length=d_measured,
        u_lattice=U,
    )
    assert u.tau == pytest.approx(tau_ref, rel=1e-12)
    assert u.nu == pytest.approx(nu_ref, rel=1e-12)
    assert u.dt == pytest.approx((U / U_PHYS_MS) * (D_PHYS_M / d_measured), rel=1e-12)
    assert u.Re == pytest.approx(RE, rel=1e-12)


