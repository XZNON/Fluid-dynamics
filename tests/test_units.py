def test_svg_flip_y_matches_png(tmp_path):
    """SVG's y points down; the solver's points up."""
    wedge = """<svg viewBox="0 0 100 100">
      <path d="M 10 10 L 90 10 L 50 40 Z"/></svg>"""
    path = write_svg(tmp_path, wedge, "wedge.svg")
    raw = from_svg(path, (101, 101), check=False, verbose=False, flip_y=False)
    down = from_svg(path, (101, 101), check=False, verbose=False, flip_y=True)

    # The wide edge is at SVG y = 10, i.e. the top of the picture. Unflipped it
    # lands in the low rows of the mask (which the renderer draws at the
    # bottom); flipped, in the high rows. The two masks are not asserted to be
    # exact mirrors: the flip happens in *coordinates*, before the even-odd
    # fill, and that fill's tie-breaking is not symmetric to the cell.
    def widest_row(mask: np.ndarray) -> int:
        return int(np.argmax(mask.sum(axis=1)))

    assert widest_row(raw) < 101 / 2 < widest_row(down)
    # Same shape either way, to within the one boundary row that even-odd's
    # half-open span rule includes on one side of the reflection and not the
    # other — the wedge's flat edge is exactly that row.
    assert abs(int(raw.sum()) - int(down.sum())) <= int(raw.sum(axis=1).max())
