"""T009 — physical <-> lattice conversion, and masks from PNG / SVG.

Covers ``lbm/units.py`` (``LatticeUnits``) and the two image sources added to
``lbm/geometry.py`` (``from_png``, ``from_svg``), one or more tests per
acceptance criterion in ``old-Docs/TASKS1.md`` § T009.

The committed test image
------------------------
``tests/data/test_body.png`` is generated by :func:`write_test_png` below —
the source of the image lives in this file so its solid-cell count is
*derivable arithmetic* rather than a magic number someone measured once and
nobody can re-check. Regenerate it with::

    myenv/Scripts/python.exe -c "import tests.test_units as t; t.write_test_png()"

Two opaque shapes on a transparent background, chosen so the expected count is
a sum of exact areas: a disc of radius :data:`PNG_RADIUS` and a rectangle of
:data:`PNG_RECT`, which do not overlap. Downscaling by an integer factor with a
box filter preserves area, so the expected cell count is the pixel area times
the area scale — see :func:`expected_solid_cells`.
"""

from __future__ import annotations

import math
import warnings
from pathlib import Path

import numpy as np
import pytest

from lbm.geometry import MaskWarning, bounding_box, from_png, from_svg, min_thickness
from lbm.units import (
    BLUFF_BODY_SPEEDUP,
    TAU_FLOOR,
    U_LATTICE_MAX,
    LatticeUnits,
)

DATA = Path(__file__).parent / "data"
PNG_PATH = DATA / "test_body.png"

# --- the committed test image, as arithmetic ---------------------------------

PNG_SIZE = 256  # pixels, square
PNG_CENTRE = (128.0, 128.0)  # (x, y) in pixels
PNG_RADIUS = 64.0  # pixels
PNG_RECT = (200, 40, 240, 60)  # (x0, y0, x1, y1), half-open, pixels
GRID = (128, 128)  # (ny, nx) the tests load it onto — exactly half


def expected_solid_cells(ny: int = GRID[0], nx: int = GRID[1]) -> float:
    """Solid cells the image *should* produce on an ``(ny, nx)`` grid.

    Area is preserved by a box-filter resample followed by a 0.5 threshold, so
    this is the pixel area of the two shapes times the area scale factor. The
    disc contributes ``pi r^2`` and the rectangle ``w * h``; they do not
    overlap by construction.
    """
    disc = math.pi * PNG_RADIUS**2
    x0, y0, x1, y1 = PNG_RECT
    rect = (x1 - x0) * (y1 - y0)
    scale = (ny / PNG_SIZE) * (nx / PNG_SIZE)
    return (disc + rect) * scale


def write_test_png(path: Path = PNG_PATH) -> Path:
    """Generate ``tests/data/test_body.png``. The source of the committed image.

    RGBA: a white disc and a white rectangle at full alpha on a fully
    transparent background, so ``from_png`` takes the **alpha** path.
    """
    from PIL import Image

    path.parent.mkdir(parents=True, exist_ok=True)
    y, x = np.mgrid[0:PNG_SIZE, 0:PNG_SIZE].astype(np.float64)
    cx, cy = PNG_CENTRE
    disc = (x - cx) ** 2 + (y - cy) ** 2 <= PNG_RADIUS**2
    x0, y0, x1, y1 = PNG_RECT
    rect = (x >= x0) & (x < x1) & (y >= y0) & (y < y1)
    solid = disc | rect

    rgba = np.zeros((PNG_SIZE, PNG_SIZE, 4), dtype=np.uint8)
    rgba[..., :3] = 255
    rgba[..., 3] = np.where(solid, 255, 0)
    Image.fromarray(rgba, mode="RGBA").save(path, optimize=True)
    return path


def load_png(**kwargs) -> np.ndarray:
    """``from_png`` on the committed image, quiet, checks off unless asked."""
    kwargs.setdefault("check", False)
    kwargs.setdefault("verbose", False)
    return from_png(PNG_PATH, GRID, **kwargs)


# --- LatticeUnits: the derivation --------------------------------------------


def test_from_physical_returns_every_derived_quantity():
    """dx, dt, tau, lattice U and Re, all five, from one physical description."""
    u = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, nu_phys=1e-3, cells_per_length=60.0, u_lattice=0.05
    )
    assert u.Re == pytest.approx(1.0 * 0.1 / 1e-3)
    assert u.dx == pytest.approx(0.1 / 60.0)
    assert u.dt == pytest.approx(0.05 * (0.1 / 60.0) / 1.0)
    assert u.U == 0.05
    assert u.tau == pytest.approx(0.5 + 3.0 * 0.05 * 60.0 / u.Re)


def test_tau_matches_the_two_forms_of_the_lattice_viscosity():
    """``nu_phys dt / dx^2`` and ``(tau - 0.5)/3`` are the same number.

    The module docstring derives the lattice viscosity twice — once by
    dimensional scaling, once from ``Re`` — and constraint 2 depends on them
    agreeing.
    """
    u = LatticeUnits.from_physical(
        u_phys=2.0, l_phys=0.2, nu_phys=4e-3, cells_per_length=80.0, u_lattice=0.04
    )
    assert u.to_lattice_viscosity(u.nu_phys) == pytest.approx(u.nu, rel=1e-12)
    assert u.nu == pytest.approx((u.tau - 0.5) / 3.0, rel=1e-12)


def test_re_from_re_and_re_from_nu_agree():
    """Describing the fluid by ``re`` or by ``nu_phys`` gives the same case."""
    a = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, nu_phys=1e-3, cells_per_length=40.0
    )
    b = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, cells_per_length=40.0
    )
    assert a.Re == pytest.approx(b.Re)
    assert a.tau == pytest.approx(b.tau)
    assert a.dt == pytest.approx(b.dt)
    assert b.nu_phys == pytest.approx(1e-3)


@pytest.mark.parametrize(
    "u_phys,l_phys,nu_phys,cells",
    [
        (20.0, 1.5, 3.0e-2, 200.0),  # Re 1000, a resolvable wing
        (1.0, 0.1, 1e-3, 60.0),  # Re 100, the Rung 3 regime
        (0.05, 0.002, 1e-6, 30.0),  # Re 100, microfluidic
        (3.0, 0.4, 1.5e-2, 500.0),  # Re 80, well resolved
    ],
)
def test_round_trip_reproduces_re_within_a_tenth_of_a_percent(
    u_phys, l_phys, nu_phys, cells
):
    """physical -> lattice -> physical reproduces Re to within 0.1%.

    ``reynolds()`` recomputes ``Re`` from ``U``, the resolution and ``tau``
    alone — no metres anywhere in that path — so agreement is a statement about
    the conversion, not about arithmetic done twice the same way.
    """
    u = LatticeUnits.from_physical(
        u_phys=u_phys, l_phys=l_phys, nu_phys=nu_phys, cells_per_length=cells
    )
    assert u.reynolds() == pytest.approx(u.Re, rel=1e-3)

    # ... and the physical quantities come back through the other conversions.
    assert u.to_physical_velocity(u.U) == pytest.approx(u_phys, rel=1e-12)
    assert u.to_physical_length(u.cells_per_length) == pytest.approx(l_phys, rel=1e-12)
    back = (
        u.to_physical_velocity(u.U)
        * u.to_physical_length(u.cells_per_length)
        / u.nu_phys
    )
    assert back == pytest.approx(u.Re, rel=1e-3)


def test_time_conversion_round_trips():
    u = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, cells_per_length=40.0
    )
    assert u.to_physical_time(u.to_lattice_time(2.5)) == pytest.approx(2.5)
    assert u.to_lattice_length(u.to_physical_length(17.0)) == pytest.approx(17.0)


def test_resolution_is_derived_when_a_target_tau_is_given():
    """The 'derives resolution' half: pass tau, get N — and it inverts exactly."""
    u = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, tau=0.6, u_lattice=0.05
    )
    assert u.tau == pytest.approx(0.6)
    assert u.cells_per_length == pytest.approx(100.0 * 0.1 / (3.0 * 0.05))
    # and going back the other way reproduces the tau that was asked for
    again = LatticeUnits.from_physical(
        u_phys=1.0,
        l_phys=0.1,
        re=100.0,
        cells_per_length=u.cells_per_length,
        u_lattice=0.05,
    )
    assert again.tau == pytest.approx(0.6)


def test_resolution_for_tau_inverts_the_tau_expression():
    u = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, cells_per_length=40.0
    )
    n = u.resolution_for_tau(0.54)
    again = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, cells_per_length=n, u_lattice=u.U
    )
    assert again.tau == pytest.approx(0.54)


