def test_a_hairline_png_is_caught_by_the_thickness_rule(tmp_path):
    """The failure this criterion exists for: a downscale that thins a wall.

    A 6-pixel-wide bar in a 256-px image is a 1.5-cell feature at 64 cells.
    Whatever survives the threshold is thinner than the 3 cells constraint 12
    demands, and ``check_mask`` says so before the run.
    """
    from PIL import Image

    rgba = np.zeros((256, 256, 4), dtype=np.uint8)
    rgba[..., :3] = 255
    rgba[40:216, 124:130, 3] = 255  # a 6-px-wide vertical bar
    path = tmp_path / "hairline.png"
    Image.fromarray(rgba, mode="RGBA").save(path)

    solid = from_png(path, (64, 64), check=False, verbose=False)
    assert solid.any(), "the bar vanished entirely; the test needs a wider bar"
    assert min_thickness(solid) < 3

    with pytest.warns(MaskWarning, match="cells thick"):
        from_png(path, (64, 64), verbose=False)


