def test_curves_are_flattened(tmp_path):
    """A cubic-Bezier circle approximation comes out round, not empty."""
    k = 0.5523 * 40.0
    circle_svg = f"""<svg viewBox="0 0 100 100"><path d="
      M 90 50 C 90 {50 + k} {50 + k} 90 50 90 C {50 - k} 90 10 {50 + k} 10 50
      C 10 {50 - k} {50 - k} 10 50 10 C {50 + k} 10 90 {50 - k} 90 50 Z"/></svg>"""
    solid = from_svg(
        write_svg(tmp_path, circle_svg, "circle.svg"), (101, 101),
        check=False, verbose=False,
    )
    # A disc of radius 40 in a 100-unit viewBox scaled to 101 cells: area
    # pi r^2 with r ~ 40 cells.
    assert int(solid.sum()) == pytest.approx(math.pi * 40.0**2, rel=0.05)
    box = bounding_box(solid)
    assert box is not None
    assert (box[1] - box[0] + 1) == pytest.approx(box[3] - box[2] + 1, abs=2)


def test_two_subpaths_make_a_hole(tmp_path):
    """Even-odd across subpaths — the documented fill rule."""
    donut = """<svg viewBox="0 0 100 100">
      <path d="M 10 10 L 90 10 L 90 90 L 10 90 Z"/>
      <path d="M 40 40 L 60 40 L 60 60 L 40 60 Z"/></svg>"""
    solid = from_svg(
        write_svg(tmp_path, donut, "donut.svg"), (101, 101), check=False, verbose=False
    )
    assert not solid[50, 50]  # the hole
    assert solid[50, 15]  # the ring


