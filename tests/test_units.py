    u = LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, tau=0.52, u_lattice=0.05
    )
    note = u.stability_note()
    assert "nan" in note.lower() or "blew up" in note.lower()
    assert "D-029" in note
    assert LatticeUnits.from_physical(
        u_phys=1.0, l_phys=0.1, re=100.0, tau=0.60, u_lattice=0.05
    ).stability_note() != note


