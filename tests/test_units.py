def test_alpha_is_preferred_over_luminance(tmp_path, capsys):
    """A white shape on a transparent field: luminance would see nothing.

    The image is white-on-transparent, so the luminance path (dark = solid)
    would return an *empty* mask. Getting the disc back is the proof that alpha
    won.
    """
    from_png(PNG_PATH, GRID, check=False, verbose=True)
    assert "alpha" in capsys.readouterr().out

    # ``invert`` flips the sense of that same alpha channel, so the two masks
    # are complements up to the cells sitting exactly on the threshold.
    normal = load_png()
    forced = from_png(PNG_PATH, GRID, check=False, verbose=False, invert=True)
    assert not (normal & forced).any()
    assert forced.sum() == pytest.approx(
        GRID[0] * GRID[1] - normal.sum(), rel=0.01
    )


def test_luminance_fallback_when_there_is_no_alpha(tmp_path):
    """A plain black-on-white image, no alpha channel: dark is solid."""
    from PIL import Image

    a = np.full((64, 64), 255, dtype=np.uint8)
    a[16:48, 8:24] = 0  # a black block, 32 x 16 px
    path = tmp_path / "gray.png"
    Image.fromarray(a, mode="L").save(path)

    solid = from_png(path, (64, 64), check=False, verbose=False)
    assert int(solid.sum()) == 32 * 16
    # flip_y is on by default, so the block's rows are mirrored.
    assert solid[64 - 48 : 64 - 16, 8:24].all()


def test_a_fully_opaque_rgba_image_falls_back_to_luminance(tmp_path):
    """Alpha that is uniformly opaque carries no shape and must not be used."""
    from PIL import Image

    rgba = np.zeros((32, 32, 4), dtype=np.uint8)
    rgba[..., 3] = 255
    rgba[..., :3] = 255
    rgba[8:24, 8:24, :3] = 0  # a dark square
    path = tmp_path / "opaque.png"
    Image.fromarray(rgba, mode="RGBA").save(path)

    solid = from_png(path, (32, 32), check=False, verbose=False)
    assert int(solid.sum()) == 16 * 16


def test_flip_y_is_what_makes_the_picture_upright():
    """Image row 0 is the top; the solver's y increases upward (LiveSink)."""
    up = load_png(flip_y=True)
    down = load_png(flip_y=False)
    assert np.array_equal(up, down[::-1, :])

    # The rectangle sits near the *top* of the picture (y = 40..60 of 256), so
    # with flip_y it must land in the upper rows of the mask.
    tail_up = np.flatnonzero(up[:, GRID[1] // 2 + 40 :].any(axis=1))
    assert tail_up.mean() > GRID[0] / 2


def test_threshold_moves_the_boundary_the_way_it_should():
    """A higher threshold keeps only cells the shape covers more fully."""
    lo = load_png(threshold=0.2)
    hi = load_png(threshold=0.8)
    assert lo.sum() >= hi.sum()
    assert np.all(hi <= lo)  # the strict mask is a subset


def test_contain_preserves_the_aspect_ratio(tmp_path):
    """``fit='contain'`` pads with fluid instead of distorting the shape."""
    from PIL import Image

    rgba = np.zeros((64, 64, 4), dtype=np.uint8)
    rgba[..., :3] = 255
    rgba[16:48, 16:48, 3] = 255  # a 32 x 32 square
    path = tmp_path / "square.png"
    Image.fromarray(rgba, mode="RGBA").save(path)

    solid = from_png(path, (64, 128), fit="contain", check=False, verbose=False)
    box = bounding_box(solid)
    assert box is not None
    y0, y1, x0, x1 = box
    assert (y1 - y0 + 1) == pytest.approx(x1 - x0 + 1, abs=1)  # still square

    stretched = from_png(path, (64, 128), fit="stretch", check=False, verbose=False)
    sbox = bounding_box(stretched)
    assert sbox is not None
    assert (sbox[3] - sbox[2] + 1) > (sbox[1] - sbox[0] + 1)  # and this one is not


