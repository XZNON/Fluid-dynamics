SQUARE_SVG = """<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
  <path d="M 20 20 L 80 20 L 80 80 L 20 80 Z"/>
</svg>
"""


def write_svg(tmp_path: Path, text: str, name: str = "shape.svg") -> Path:
    path = tmp_path / name
    path.write_text(text, encoding="utf-8")
    return path


def test_a_simple_closed_path_rasterises(tmp_path):
    """The acceptance criterion's 'at least simple closed paths'.

    The square covers 60/100 of the viewBox in each direction, so on a 101-cell
    grid fitted to the viewBox it spans about 61 cells and covers about 36% of
    the grid.
    """
    solid = from_svg(
        write_svg(tmp_path, SQUARE_SVG), (101, 101), check=False, verbose=False
    )
    assert solid.dtype == np.bool_ and solid.shape == (101, 101)
    box = bounding_box(solid)
    assert box is not None
    y0, y1, x0, x1 = box
    assert (y1 - y0 + 1) == pytest.approx(61, abs=2)
    assert (x1 - x0 + 1) == pytest.approx(61, abs=2)
    assert int(solid.sum()) == pytest.approx(61 * 61, rel=0.05)


def test_relative_commands_and_shorthands_give_the_same_square(tmp_path):
    """``m/h/v/z`` describe the same shape as ``M/L/Z``."""
    rel = """<svg viewBox="0 0 100 100"><path d="m 20 20 h 60 v 60 h -60 z"/></svg>"""
    a = from_svg(
        write_svg(tmp_path, SQUARE_SVG, "abs.svg"), (101, 101),
        check=False, verbose=False,
    )
    b = from_svg(
        write_svg(tmp_path, rel, "rel.svg"), (101, 101), check=False, verbose=False
    )
    assert np.array_equal(a, b)


